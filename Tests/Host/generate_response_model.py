#!/usr/bin/env python3
"""Rebuild the bounded 200 units/s mean heading model from its source CSV.

No smoothing, zero-yaw tail assumption, or mirrored response is introduced.
Samples are aligned by measured encoder progress, then averaged across batches.
"""
import bisect
import csv
import math
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
END = 1420.75708
ARC_END = 785.378571
BOUNDARIES = [350, 485.378571, ARC_END, 920.757142, 1270.757142, END]


def interpolate(rows, progress):
    i = bisect.bisect_right([r[0] for r in rows], progress)
    if i == 0:
        return rows[0][1]
    if i == len(rows):
        return rows[-1][1]
    a, b = rows[i-1], rows[i]
    return a[1] + (b[1]-a[1])*(progress-a[0])/(b[0]-a[0])


def generate():
    batches = {}
    with (ROOT/'exp/response_model/forward_4500_200.csv').open() as stream:
        for row in csv.DictReader(stream):
            # Last observation at duplicated progress (preparation) wins.
            batches.setdefault(int(row['batch']), {})[float(row['progressMm'])] = float(row['yawDeg'])
    runs = [sorted(values.items()) for values in batches.values()]
    assert len(runs) == 3 and all(run[-1][0] >= END for run in runs)
    origins = [interpolate(run, 0) for run in runs]
    def heading(s):
        return math.radians(sum(interpolate(run, s)-origin for run, origin in zip(runs, origins))/len(runs))
    nodes = sorted(set([0., *range(10, int(END), 10), *BOUNDARIES]))
    steady = (heading(ARC_END)-heading(ARC_END-150))/150
    text = '/* Generated by Tests/Host/generate_response_model.py. Do not hand edit. */\n'
    text += f'#define RESPONSE_STEADY_CURVATURE {steady:.10f}f\n'
    text += 'static const ResponseHeadingNode responseHeading[] = {\n'
    text += ''.join(f'    {{{s:.6f}f, {heading(s):.10f}f}},\n' for s in nodes)
    text += '};\n'
    (ROOT/'Controllers/Src/MotionResponseModel.inc').write_text(text)
    print(f'{len(nodes)} nodes; base endpoint {math.degrees(heading(END)):.3f} deg; steady radius {1/steady:.2f} mm')


if __name__ == '__main__':
    generate()
